"""Data model for documents, projects, chunks and API requests."""
from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Literal

from pydantic import BaseModel, Field


class DocType(str, Enum):
    """Kind of document in the index."""
    research_project = "research_project"
    research_paper = "research_paper"
    research_notes = "research_notes"
    # REQ-38: legal texts (legal ontology, app/legal/)
    legal_project = "legal_project"       # a folder like a research project; the versions of the law are its stages
    legal_guideline = "legal_guideline"   # formal guidelines of authorities (Commission communications, C(…)) – soft law
    guidance = "guidance"                 # REQ-48: guidance & FAQ – Q&A pages, factsheets, explanations by authorities (not binding)
    standard = "standard"                 # norms/standards (ISO, IEC, CEN, DIN …)


class ProjectRole(str, Enum):
    """Role of a file within a research project."""
    manuscript = "manuscript"
    abstract = "abstract"
    title_page = "title_page"
    cover_letter = "cover_letter"
    reviewer_response = "reviewer_response"
    highlights = "highlights"
    appendix = "appendix"
    tables = "tables"
    figures = "figures"
    submission_pdf = "submission_pdf"      # PDF generated by the journal / proof
    questionnaire = "questionnaire"
    data = "data"
    analysis_script = "analysis_script"
    analysis_output = "analysis_output"
    model_file = "model_file"              # simulation/HLM models
    notes = "notes"
    presentation = "presentation"
    image = "image"
    reference = "reference"                # cited third-party literature in the project
    legal_text = "legal_text"              # REQ-38: a version of the law / guideline / standard itself
    white_paper = "white_paper"            # REQ-51: white paper or similar – political precursor document of a legal project
    other = "other"


class StructuredSummary(BaseModel):
    """Structured abstract following the Emerald scheme. Created for all data types."""
    purpose: str | None = Field(None, description="Purpose – Ziel/Fragestellung")
    design_methodology_approach: str | None = Field(None, description="Design/Methodology/Approach")
    findings: str | None = Field(None, description="Findings – zentrale Ergebnisse")
    research_limitations_implications: str | None = Field(None, description="Research limitations/implications")
    originality_value: str | None = Field(None, description="Originality/value")
    practical_implications: str | None = Field(None, description="Practical implications (optional)")
    source: Literal["parsed", "llm", "manual", "inherited"] | None = None
    source_doc_id: str | None = None

    def is_empty(self) -> bool:
        """True when no summary field is filled."""
        return not any([self.purpose, self.design_methodology_approach, self.findings,
                        self.research_limitations_implications, self.originality_value])


class MethodTag(BaseModel):
    """Classification against the methods glossary (glossary/methods.yaml)."""
    id: str
    label: str
    confidence: float = 1.0
    source: Literal["keyword", "llm", "manual"] = "keyword"
    evidence: str | None = None


class ProjectContext(BaseModel):
    """Extra metadata that only files of a research project get."""
    project_id: str
    project_name: str                 # = Ordnername
    rel_path: str                     # path relative to the project folder
    folder: str                       # subfolder ("" = root)
    role: ProjectRole = ProjectRole.other
    venue: str | None = None          # e.g. journal name from Journal/<n> <Name>
    submission_no: int | None = None  # running number of the submission
    stage: str | None = None          # initial_submission | revision_1 | ...
    version_group: str | None = None  # e.g. "artikel"
    version: str | None = None        # e.g. "54", "27a"
    version_num: int | None = None
    is_latest: bool = True
    archived: bool = False            # lies in alt/old/archiv
    duplicate_of: str | None = None   # the same file (hash) already exists


class DocumentRecord(BaseModel):
    """Metadata of one indexed file (stored as the Qdrant document payload)."""
    doc_id: str
    doc_type: DocType
    title: str
    filename: str
    filetype: str                     # file extension without dot, lower case
    mime: str | None = None
    size_bytes: int
    sha256: str
    content_hash: str | None = None   # fingerprint of the text (without digits/whitespace) – detects repeated exports
    duplicate_of: str | None = None   # the same file or the same content already exists
    summary_key: str | None = None    # hash of the text behind the summary vector (clustering)
    date: datetime | None = None      # best available date
    date_source: str | None = None    # doc_properties | pdf_metadata | filename | file_mtime
    year: int | None = None
    created: datetime | None = None
    modified: datetime | None = None
    authors: list[str] = []
    editors: list[str] = []                     # REQ-19: names from file metadata (last saved by) – not authors
    doi: str | None = None            # recognised from the text (papers)
    language: str | None = None
    pages: int | None = None
    text_chars: int = 0
    indexed: bool = False             # chunks in the vector index?
    index_note: str | None = None     # why not indexed
    project: ProjectContext | None = None
    legal: dict | None = None         # REQ-38: {norm_id, norm_title, kind, eli, seq, stage, in_force, valid_to, applicable, …}
    summary: StructuredSummary = Field(default_factory=StructuredSummary)
    methods: list[MethodTag] = []
    keywords: list[str] = []
    databases: list[str] = []         # AL, CNN_DM, DL, JSW, LDK, ML, UM … (one or more)
    source_path: str                  # absolute path of the original file
    ingested_at: datetime = Field(default_factory=datetime.utcnow)

    def payload(self) -> dict:
        """Flat payload for Qdrant (filter fields at the top level)."""
        d = self.model_dump(mode="json")
        p = self.project
        d.update(
            project_name=p.project_name if p else None,
            project_id=p.project_id if p else None,
            role=p.role.value if p else None,
            venue=p.venue if p else None,
            stage=p.stage if p else None,
            is_latest=p.is_latest if p else True,
            archived=p.archived if p else False,
            method_ids=[m.id for m in self.methods],
            date_ts=int(self.date.timestamp()) if self.date else None,
        )
        return d


class ProjectRecord(BaseModel):
    """Metadata of a research project folder (stored in the projects collection)."""
    project_id: str
    name: str
    source_path: str
    file_count: int
    indexed_count: int
    filetypes: dict[str, int]
    roles: dict[str, int]
    date_from: datetime | None = None
    date_to: datetime | None = None
    date: datetime | None = None                # overall date set at upload ("Add new data")
    venues: list[str] = []
    title: str | None = None
    authors: list[str] = []
    keywords: list[str] = []
    summary: StructuredSummary = Field(default_factory=StructuredSummary)
    methods: list[MethodTag] = []
    excluded_patterns: list[str] = []
    excluded_count: int = 0                     # files skipped by excluded_patterns (e.g. literature folders)
    excluded_by: dict[str, int] = {}            # pattern -> number of files it excluded
    databases: list[str] = []
    ingested_at: datetime = Field(default_factory=datetime.utcnow)


class Chunk(BaseModel):
    """A text chunk of a document with its position and rhetorical role."""
    chunk_id: str
    doc_id: str
    text: str
    locator: str | None = None    # locator as written into the source, e.g. "S. 4", "Folie 3", "Blatt Daten"
    page: int | None = None
    ordinal: int = 0
    section: str | None = None    # section heading (DoCO: Section)
    deo: list[str] = []           # rhetorical role(s) (DEO), e.g. ["Materials", "Methods"]
    deo_source: str | None = None # "heading" | "llm" | None


# ----------------------------------------------------------------- API
class SearchFilters(BaseModel):
    """Filters a user can set for search and chat."""
    database: list[str] = []          # empty = all databases
    cluster: list[int] = []           # cluster ids from the last clustering run
    deo: list[str] = []               # rhetorical role of the passage (Discourse Elements Ontology), e.g. Methods
    doc_ids: list[str] = []           # only these documents (Graph RAG narrows the search to the graph path this way)
    doc_type: list[DocType] = []
    project: list[str] = []
    person: list[str] = []            # REQ-19: only data of these person(s) – own papers/notes + projects whose team they are in
    filetype: list[str] = []
    role: list[str] = []
    method: list[str] = []
    venue: list[str] = []
    year_from: int | None = None
    year_to: int | None = None
    latest_only: bool = False
    include_archived: bool = True
    # REQ-37: state of legal texts (laws, guidelines, standards). Empty = the version in force today.
    as_of: str | None = None          # reference date YYYY-MM-DD: versions that were in force on that day
    legal_stage: str | None = None    # stage in the procedure, e.g. proposal (drafts are not in force)
    legal_from: str | None = None     # period for changes (actions), e.g. "since 2024"
    legal_all_versions: bool = False  # search all versions (no reference date)


class ChatTurn(BaseModel):
    """One turn of the chat history."""
    role: Literal["user", "assistant"]
    content: str


class ChatRequest(BaseModel):
    """Request of the RAG chat."""
    message: str
    filters: SearchFilters = Field(default_factory=SearchFilters)
    top_k: int = Field(6, ge=1, le=30)
    model: str | None = None              # deprecated, ignored: the model is fixed (CHAT_MODEL)
    history: list[ChatTurn] = []          # conversation so far = memory
    system_prompt: str | None = Field(None, max_length=8000,
                                      description="Custom system prompt from the front end; empty = default")
    overview: bool = Field(False, description="REQ-12: map scope (nothing selected) – add an overview of all projects "
                                              "and clusters in the selected databases, so top-level questions about all projects can be answered")


class SourceRef(BaseModel):
    """One numbered source of a chat answer."""
    n: int
    doc_id: str
    title: str
    filename: str
    url: str
    locator: str | None = None
    score: float
    snippet: str
    doc_type: str
    project_name: str | None = None
    filetype: str
    year: int | None = None
    role: str | None = None
    methods: list[str] = []
    databases: list[str] = []
    cluster_id: int | None = None
    cluster_label: str | None = None
    legal: dict | None = None         # REQ-38: component, version, validity and start of application of a legal passage


class ChatResponse(BaseModel):
    """Answer of the RAG chat with sources and metadata."""
    answer: str
    sources: list[SourceRef]
    applied_filters: SearchFilters
    prompt_filters: list[str] = []
    model: str
    intent: str | None = None          # intent of the question (for the chat history)
    entities: list[dict] = []          # recognised entities: {"type": ..., "value": ...}
    system_prompt_source: str = "default"   # "default" | "custom": which system prompt steered the answer
    system_prompt_id: str | None = None     # fingerprint of the effective prompt (chat history)
    memory_turns: int = 0                   # how many earlier turns went along as memory
    retrieval_query: str | None = None      # search query for the vector search (follow-up questions with context)
    scope: str | None = None                # REQ-12: "map" when the question was asked about the whole map without a selection
    usage: dict | None = None               # tokens and cost (EUR) of question and answer
    progress: dict | None = None            # REQ-16/18: stages of insight of the project (table below the answer)
    temporal: dict | None = None            # REQ-37: reference date/stage and the rule by which versions of legal texts were chosen
    legal: dict | None = None               # REQ-37: changes/provenance from the actions (table below the answer)


# ----------------------------------------------------------------- IDs
import uuid as _uuid  # noqa: E402


def make_project_id(name: str) -> str:
    """Stable project id (uuid5) from the project name."""
    return str(_uuid.uuid5(_uuid.NAMESPACE_URL, f"project:{name}"))


def make_doc_id(doc_type: str, scope: str, rel_path: str) -> str:
    """Stable across re-ingestion: same path -> same id (upsert instead of a duplicate)."""
    return str(_uuid.uuid5(_uuid.NAMESPACE_URL, f"{doc_type}:{scope}:{rel_path}"))
