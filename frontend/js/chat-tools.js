function histFilename(tile,sx){
  const d=new Date(sx?(sx.updated||sx.ts):Date.now()),p=n=>String(n).padStart(2,'0');
  const stamp=`${d.getFullYear()}-${p(d.getMonth()+1)}-${p(d.getDate())}_${p(d.getHours())}${p(d.getMinutes())}`;
  const slug=sx?(sx.title||'conversation').toLowerCase().replace(/[^a-z0-9äöüß]+/gi,'-').replace(/^-+|-+$/g,'').slice(0,40):'all-conversations';
  return `alita_${tile==='rag'?'document-chat':'graph-chat'}_${slug||'conversation'}_${stamp}.txt`;
}
