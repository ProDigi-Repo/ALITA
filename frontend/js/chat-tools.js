/* REQ-12 – context-dependent chat scope: a selected project (project card open) restricts both chats to that project;
   selected clusters restrict them to those clusters; nothing selected = the whole knowledge map, with an overview of
   all projects and clusters so that top-level questions about all projects can be answered. */
function chatScope(){
  const pj=(typeof CG!=='undefined'&&CG.proj)||null;
  const person=typeof PERSON!=='undefined'?[...PERSON]:[];
  if(pj)return {kind:'project',project:[pj],cluster:[],overview:false,person};
  const cl=(typeof CV!=='undefined'&&CV.sels.size)?[...CV.sels]:[];
  if(cl.length)return {kind:'clusters',project:[],cluster:cl,overview:false,person};
  return {kind:'map',project:[],cluster:[],overview:!person.length,person};
}
