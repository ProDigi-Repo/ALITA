// Demo: the prepared answer is streamed word by word, like a model would
function simulateStream(chat,typingEl,a,done){
  const words=String(a.answer||'').split(/(\s+)/);let i=0,b=null;
  setTimeout(function tick(){
    if(!b){typingEl.remove();b=streamBubble(chat)}
    const n=2+Math.floor(Math.random()*3);b.push(words.slice(i,i+n*2).join(''));i+=n*2;
    if(i<words.length)setTimeout(tick,18+Math.random()*22);else setTimeout(()=>{b.remove();done()},60);
  },350);
}
// Live: Server-Sent Events from /api/chat/stream (meta → delta … → done | error)
async function streamChat(body,chat,typingEl,url='api/chat/stream'){
  const r=await fetch(url,{method:'POST',headers:headers(),body:JSON.stringify(body)});
  if(r.status===404||r.status===405)return {fallback:true};
  if(!r.ok||!r.body){let m='Error '+r.status;try{m=(await r.json()).detail||m}catch(e){}return {error:m}}
  const reader=r.body.getReader(),dec=new TextDecoder();let buf='',bubble=null,meta=null,done=null,error=null;
  while(true){
    const {value,done:end}=await reader.read();if(end)break;
    buf+=dec.decode(value,{stream:true});let k;
    while((k=buf.indexOf('\n\n'))>=0){
      const raw=buf.slice(0,k);buf=buf.slice(k+2);let ev='message',data='';
      raw.split('\n').forEach(l=>{if(l.startsWith('event:'))ev=l.slice(6).trim();else if(l.startsWith('data:'))data+=l.slice(5).trim()});
      let obj={};try{obj=JSON.parse(data||'{}')}catch(e){}
      if(ev==='meta')meta=obj;
      else if(ev==='delta'){if(!bubble){typingEl.remove();bubble=streamBubble(chat)}bubble.push(obj.t||'')}
      else if(ev==='done')done=obj;
      else if(ev==='error')error=obj.detail||'Streaming failed';
    }
  }
  if(!bubble)typingEl.remove();else bubble.remove();
  if(error&&!done)return {error,partial:bubble?bubble.text():''};
  return {data:done||{...(meta||{}),answer:bubble?bubble.text():'',sources:[]}};
}


