"""Frontend build helper (no Node needed).

    python tools/build_frontend.py data                      # js/data.js und css/databases.css neu erzeugen
    python tools/build_frontend.py artifact DEMO.json OUT.html   # eine einzelne, eigenständige Seite bauen (CSS/JS inline, Demodaten)

Die App selbst braucht keinen Build: nginx bzw. das Backend liefern frontend/ direkt aus (index.html, css/, js/).
`data` hält die Offline-Fallbacks (Release Notes, ISO/EU-AI-Act-Doku, Technical Documentation, Standard-System-Prompts,
Datenbank-Registry) und die Datenbankfarben (css/databases.css, aus backend/app/registry.py) mit den Quellen synchron; `artifact` erzeugt die veröffentlichte Demo-Seite ohne Backend.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONT = ROOT / "frontend"


def _js(obj) -> str:
    return json.dumps(obj, ensure_ascii=False).replace("</", "<\\/")


def _docs(folder: Path) -> list[dict]:
    out = []
    for f in sorted(folder.glob("*.md")):
        t = f.read_text(encoding="utf-8")
        title = next((line[2:].strip() for line in t.splitlines() if line.startswith("# ")), f.stem)
        out.append({"id": f.stem, "title": title, "markdown": t})
    return out


def build_database_css(registry) -> Path:
    """--db-<ID> colour variables: light theme, dark theme (system or chosen) and the always-dark surfaces."""
    def block(selector: str, key: str, extra: str = "") -> str:
        return selector + "{\n" + "".join(f"  --db-{d.id}:{getattr(d, key)};\n" for d in registry) + extra + "}\n"
    out = FRONT / "css" / "databases.css"
    out.write_text(
        "/* GENERATED by tools/build_frontend.py from backend/app/registry.py – do not edit by hand */\n"
        + block(":root", "color")
        + "@media (prefers-color-scheme: dark){\n" + block(':root:not([data-theme="light"])', "color_dark") + "}\n"
        + block(':root[data-theme="dark"]', "color_dark")
        + "/* surfaces that are always dark: database bar, 3D cluster space */\n"
        + block(".dbbar,.s3", "color_dark"),
        encoding="utf-8")
    return out


def build_data() -> Path:
    sys.path.insert(0, str(ROOT / "backend"))
    from app.prompts import DEFAULTS
    from app.registry import DEFAULTS as DATABASES
    from app.release_notes import load

    releases = load(ROOT / "CHANGELOG.md")
    compliance = _docs(ROOT / "docs" / "compliance")
    tech = []
    base = ROOT / "docs" / "technical"
    for folder in sorted(x for x in base.iterdir() if x.is_dir()) if base.is_dir() else []:
        docs = [{**d, "id": f"{folder.name}/{d['id']}"} for d in _docs(folder)]
        tech.append({"id": folder.name, "title": folder.name.replace("-", " ").title(), "docs": docs})
    out = FRONT / "js" / "data.js"
    out.write_text(
        "/* GENERATED by tools/build_frontend.py from CHANGELOG.md, docs/, backend/app/prompts.py and backend/app/registry.py – do not edit by hand */\n"
        f"const RELEASES_FALLBACK={_js(releases)};\n"
        f"const COMPLIANCE_FALLBACK={_js(compliance)};\n"
        f"const SYS_DEFAULT={_js(DEFAULTS)};\n"
        f"const TECH_FALLBACK={_js(tech)};\n"
        f"const DB_REGISTRY={_js([d.public_dict() for d in DATABASES])};\n",
        encoding="utf-8",
    )
    css = build_database_css(DATABASES)
    print(f"{css.relative_to(ROOT)}: {len(DATABASES)} databases")
    print(f"{out.relative_to(ROOT)}: releases {[r['version'] for r in releases][:3]}…, {len(compliance)} compliance docs, "
          f"{sum(len(g['docs']) for g in tech)} technical docs")
    return out


def build_artifact(demo_json: Path, out: Path) -> Path:
    s = (FRONT / "index.html").read_text(encoding="utf-8")
    body = s[s.index("<!--APP-START-->") + len("<!--APP-START-->"): s.index("<!--APP-END-->")]
    body = re.sub(r'<link rel="stylesheet" href="(css/[\w.-]+)">',
                  lambda m: "<style>\n" + (FRONT / m.group(1)).read_text(encoding="utf-8") + "</style>", body)
    body = re.sub(r'<script src="(js/[\w.-]+)"></script>',
                  lambda m: "<script>\n" + (FRONT / m.group(1)).read_text(encoding="utf-8") + "</script>", body)
    body = body.replace("</head>\n<body><!--BODY-->\n", "")
    body = '<meta charset="utf-8">' + body   # the page may be opened as a plain file, too
    body = body.replace("/*__DEMO_DATA__*/", "window.DEMO_DATA=" + demo_json.read_text(encoding="utf-8") + ";")
    out.write_text(body, encoding="utf-8")
    print(f"{out}: {len(body):,} bytes")
    return out


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "data":
        build_data()
    elif len(sys.argv) == 4 and sys.argv[1] == "artifact":
        build_data()
        build_artifact(Path(sys.argv[2]), Path(sys.argv[3]))
    else:
        sys.exit(__doc__)
